//! Этап 5 — REALITY: крипто-примитивы клиентской части и кастомная
//! проверка сертификата вместо цепочки доверия PKI.
//!
//! # Что реально сделано и проверено
//! - `auth`: X25519 ECDH, HKDF-SHA256(AuthKey), AES-256-GCM
//!   seal/open поля SessionId, HMAC-SHA512 проверка сертификата —
//!   байт-в-байт сверено с исходниками XTLS/Xray-core
//!   (`transport/internet/reality/reality.go`, клиентский Seal) и
//!   XTLS/REALITY (`tls.go`, серверный симметричный Open) — оба
//!   независимо цитируют одни и те же salt/info/nonce/AAD. Плюс
//!   покрыто тестами: официальный тестовый вектор X25519 из RFC 7748
//!   §6.1 (перепроверен самостоятельно через `cryptography` на
//!   Python перед тем, как попасть в Rust-тест — см. историю), и
//!   раунд-трип seal/open, реализованный НЕЗАВИСИМО двумя разными
//!   вызовами AEAD (наш `compute()` и отдельная функция `open()` в
//!   тестах), чтобы не проверять код сам на себе одним и тем же путём.
//! - `verifier`: `rustls::client::danger::ServerCertVerifier`, который
//!   заменяет проверку цепочки доверия (PKI) на HMAC-SHA512-проверку
//!   из `auth`, но НЕ трогает остальную криптографию TLS 1.3 —
//!   подпись в Certificate/CertificateVerify по-прежнему проверяется
//!   по-настоящему (иначе сервер, даже не владеющий приватным ключом
//!   сертификата, мог бы завершить рукопожатие; см. `verifier.rs`).
//!
//! # Вставка SessionId в реальный ClientHello — боевой механизм
//! Первая проверка (см. поправку ниже) была спайком через
//! `ClientSessionStore`: если он вернёт фейковую TLS1.2-сессию с нужным
//! нам `SessionId`, rustls честно копирует этот `SessionId` в исходящий
//! ClientHello. Это доказало, что патченный rustls МОЖЕТ доставить
//! произвольный SessionId на провод (тест `core/tests/reality_session_id_spike.rs`,
//! всё ещё проходит) — но оказалось НЕ тем механизмом для полного REALITY:
//! `ClientSessionStore::tls12_session()` вызывается ДО генерации
//! `ClientHello.random`, а AuthKey и nonce AES-GCM зависят именно от
//! `random`. Плюс REALITY требует переиспользовать ОДИН И ТОТ ЖЕ
//! эфемерный X25519-секрет дважды (ECDH с REALITY-сервером для AuthKey,
//! и позже настоящий TLS1.3 ECDH с сервером из SNI) — `ClientSessionStore`
//! вообще не участвует в выборе key_share.
//!
//! Боевой путь — новый трейт `rustls::client::RealityClientHook`
//! (`ClientConfig::reality: Option<Arc<dyn RealityClientHook>>`),
//! добавленный патчем в `vendor/rustls-reality-patch/src/client/{client_conn,hs}.rs`
//! и реализованный клиентской стороной в [`hook::RealityHook`]. Патч
//! подключается в `emit_client_hello_for_retry` — единственной функции
//! rustls, которая реально собирает и отправляет ClientHello — в трёх
//! точках: (1) key_share подменяется на обёртку над нашим эфемерным
//! секретом (`RealityKeyExchange`, реализует `ActiveKeyExchange`); (2)
//! `named_groups` на исходном hello сужен до одного X25519, чтобы не
//! спровоцировать HelloRetryRequest несоответствием заявленных групп
//! реально отправленному key_share; (3) уже зная настоящий
//! `ClientHello.random`, SessionId на месте шифруется (AAD = байты
//! самого этого ClientHello с обнулённым полем SessionId) и записывается
//! обратно и в тело сообщения, и в `input.session_id` (нужно для RFC 8446
//! §4.1.2 — HRR обязан эхом повторить тот же `legacy_session_id`).
//! Байт-в-байт сверено с `reality.go` из Xray-core (получен напрямую
//! через `curl` по сырому исходнику, не через пересказ). Подробный разбор
//! обеих эмпирически найденных ошибок по пути (несовпадение
//! `named_groups`/HRR; баг восстановления AAD в самом тесте) — в PLAN.md,
//! Этап 5, и в комментариях `hook.rs`/`vendor/rustls-reality-patch/src/client/hs.rs`.
//!
//! Подтверждено полным TLS1.3-рукопожатием на настоящем TCP-loopback
//! (`core/tests/reality_handshake.rs`): рукопожатие завершается,
//! приложенческие данные проходят в обе стороны, и НЕЗАВИСИМО (без
//! переиспользования кода `reality-core`) реализованная серверная
//! сторона расшифровывает перехваченный SessionId тем же AuthKey — то
//! есть клиент и независимый наблюдатель приходят к одному и тому же
//! секрету не только "по коду", но и по факту байт на проводе.
//! `transport::tcp_tls::connect_tls_by_security` подключает этот механизм
//! ко всем трём транспортам (TCP/WS/gRPC): `security=reality` в ссылке —
//! рабочий путь для каждого из них.
//!
//! **Обновление:** для WS/gRPC теперь ТОЖЕ подтверждён полный хендшейк,
//! не только факт исполнения REALITY-пути — `core/tests/reality_full_stack.rs`
//! (три теста: TCP/WS/gRPC) гоняет боевые `connect_and_handshake`/
//! `connect_and_handshake_ws`/`connect_and_handshake_grpc` против
//! настоящего динамического REALITY-сервера внутри теста (серверная
//! сторона патченного `rustls` расширена — `ClientHello::client_random()`/
//! `client_key_share_x25519()` — чтобы можно было на лету посчитать AuthKey
//! и подписать сертификат HMAC-SHA512, как это делает настоящий
//! Xray-core-сервер), то есть все три транспорта теперь проходят проверку
//! ЧЕРЕЗ настоящий `RealityCertVerifier`, а не в обход него. Подробности
//! (включая найденный и исправленный баг зависания gRPC-теста — не в
//! продакшн-коде, а в самом тесте, из-за отсутствия обязательного
//! 2-байтного заголовка VLESS-ответа) — в PLAN.md, Этап 5.
//!
//! ✅ **Находка про X25519MLKEM768 закрыта.** Текущие (26.9.8+) серверы
//! Xray-core REALITY требуют гибридный постквантовый key_share
//! `X25519MLKEM768` первым в списке вместо голого X25519 — независимо
//! подтверждено багрепортами трёх других REALITY-клиентов на той же
//! версии сервера (ссылки в PLAN.md, Этап 5). [`hook::RealityHook`]
//! теперь генерирует ещё и пару ключей ML-KEM-768 (крейт `ml-kem`,
//! pure-Rust FIPS 203 от RustCrypto) и отдаёт гибридный key_share (1216
//! байт: ML-KEM768 encapsulation key || X25519); `RealityKeyExchange` в
//! патче rustls жёстко объявляет группу `X25519MLKEM768` (кодпоинт уже
//! был известен rustls нативно). REALITY-аутентификация (AuthKey) этого
//! не касается — как была чистым X25519 ECDH с REALITY-сервером, так и
//! осталась; гибрид нужен только для настоящего TLS1.3-обмена ключами.
//! Порядок байт и склейки секретов (`mlkem || ecdh`) сверен с двумя
//! независимыми источниками: `crypto/tls`/`crypto/mlkem` из стандартной
//! библиотеки Go и собственная реализация этой же группы внутри
//! используемого в проекте rustls (`aws-lc-rs`, поддерживает её нативно
//! с `prefer-post-quantum`) — оба совпадают байт-в-байт. Все тесты
//! `reality_full_stack.rs`/`reality_handshake.rs` проходят с гибридным
//! key_share без изменения своей проверочной логики. Подробности — в
//! PLAN.md, Этап 5.
//!
//! ✅ **Находка про `minClientVer`/`maxClientVer` тоже закрыта.** Раньше
//! это был "менее уверенный" пункт (один неоднозначный багрепорт) — но
//! при прямой проверке исходника серверной части (`XTLS/reality`,
//! `tls.go`) выяснилось, что это реальный, активный код: сервер
//! сравнивает версию из plaintext-блока SessionId с
//! `config.MinClientVer`/`MaxClientVer`, и при несовпадении НЕ шлёт
//! alert — просто не помечает соединение как REALITY и прозрачно
//! проксирует байты на сайт прикрытия (для клиента это неотличимо от
//! провала хендшейка без диагностики). Проверка по-прежнему опциональна
//! (пропускается, если админ явно не задал эти поля — нулевое значение
//! `[]byte` в Go), но раз код реален, а цена правки — три байта, клиент
//! ([`auth::build_plaintext`]) теперь объявляет версию `26.9.9`
//! (актуальную на момент этой правки ветку `main` Xray-core) вместо
//! нулей. Число не синхронизировано с апстримом автоматически и будет
//! стареть — сознательный компромисс, не забытая работа; см.
//! `auth::CLIENT_VERSION` и PLAN.md, Этап 5.
//!
//! Это не отменяет архитектурный вопрос Этапа 3 (браузерная эмуляция
//! cipher suite/extension order/GREASE по-прежнему требует либо
//! `craftls`, либо перехода на другой TLS-стек) — но конкретно
//! REALITY-часть больше не упирается ни в стену построения ClientHello,
//! ни (после X25519MLKEM768 выше) в отставание от текущего протокола
//! сервера, известное на момент этой сессии.
//!
//! Поправка: раньше здесь было написано, что `refraction-networking/utls`
//! (зависимость REALITY-клиента в Xray-core) идёт через FFI на BoringSSL
//! — неверно, это форк самой стандартной библиотеки Go (`crypto/tls`),
//! не обвязка над BoringSSL. Оставлено как явная поправка, не тихо
//! исправлено.
//!
//! ⚠️ **Крипто-ревью не проводилось.** Собственный план пользователя
//! требует стороннего криптографического ревью этого этапа "до начала,
//! не после" (PLAN.md, Этап 5). Пользователь явно подтвердил только
//! оценку юридического риска — про крипто-ревью речи не было. Ниже —
//! добросовестная попытка implementation, перепроверенная против
//! первоисточников и стандартных тестовых векторов настолько, насколько
//! это можно сделать соло (включая свежую сверку формул с live-веткой
//! Xray-core и полные end-to-end тесты через настоящий верификатор для
//! всех трёх транспортов), но она не заменяет независимое ревью,
//! особенно учитывая, что ошибка здесь (по формулировке самого плана)
//! "не ломает функциональность, а молча снижает анонимность" — то есть
//! баг может годами не проявляться внешне. Риск стал ощутимее с
//! переходом на `RealityClientHook`: патч теперь не три строки
//! видимости, а рабочая логика внутри сборки ClientHello (подмена
//! key_share, AAD, запись session_id) — поверхность для потенциальной
//! ошибки заметно больше, чем на момент первой (спайковой) версии.
//! Секретный материал (`RealityHook`) теперь оборачивается в
//! `zeroize::Zeroizing` (стирается из памяти при `Drop`) — устраняет
//! один конкретный класс риска, но не заменяет ревью в целом.

//! ✅ **Сайты-приманки без ML-KEM (2026-09-26).** Клиент слал в key_share
//! только гибрид `X25519MLKEM768`; сайт без постквантовой группы (обычный
//! OpenSSL < 3.5) не мог его выбрать, и сервер REALITY отвечал "target sent
//! incorrect server hello" — соединения не было вовсе. Теперь, как у
//! Chrome, X25519-часть гибрида идёт ещё и отдельной долей (тот же ключ,
//! поэтому AuthKey не меняется), а сервер, выбравший X25519, завершает
//! обычный ECDH (`RealityClientHook::complete_x25519`). Проверено против
//! настоящего Xray-core с таким сайтом (`core/tests/interop_xray.rs`).
//!
//! ✅ **ML-DSA-65 (`pqv=`).** Если в ссылке есть ключ сервера, кроме HMAC
//! проверяется постквантовая подпись в сертификате: ML-DSA-65 над
//! HMAC-SHA512(AuthKey; ключ сертификата || ClientHello || ServerHello),
//! как `VerifyPeerCertificate` в Xray-core (`verifier.rs`). Сырые
//! ClientHello/ServerHello хук получает от патча rustls. Проверено против
//! Xray-core, включая отказ при чужом ключе.

