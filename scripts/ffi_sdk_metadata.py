"""Generate relocatable CMake and pkg-config metadata for a packaged C SDK."""

from __future__ import annotations

import re
import shlex
from pathlib import Path


PC_PLATFORMS = {"linux-x86_64", "macos-arm64"}
SAFE_LINK_ARGUMENT = re.compile(
    r"(?:-l[A-Za-z0-9_+.:-]+|-pthread|-Wl,[A-Za-z0-9_.,=+-]+|(?i:/DEFAULTLIB:[A-Za-z0-9_.+-]+))"
)
SAFE_WINDOWS_LIBRARY = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.+-]*\.lib", re.IGNORECASE)
SAFE_FRAMEWORK = re.compile(r"[A-Za-z][A-Za-z0-9_.+-]*")


def validate_link_arguments(arguments: list[str]) -> list[str]:
    """Reject paths and malformed tokens that would make metadata non-portable."""
    result: list[str] = []
    index = 0
    while index < len(arguments):
        argument = arguments[index]
        if argument == "-framework":
            if index + 1 >= len(arguments) or not SAFE_FRAMEWORK.fullmatch(arguments[index + 1]):
                raise ValueError("-framework must be followed by a framework name")
            result.extend((argument, arguments[index + 1]))
            index += 2
            continue
        if not (SAFE_LINK_ARGUMENT.fullmatch(argument) or SAFE_WINDOWS_LIBRARY.fullmatch(argument)):
            raise ValueError(f"unsupported or non-relocatable native link argument: {argument!r}")
        result.append(argument)
        index += 1
    return result


def _cmake_quote(value: str) -> str:
    delimiter = "="
    while f"]{delimiter}]" in value:
        delimiter += "="
    return f"[{delimiter}[{value}]{delimiter}]"


def _cmake_target(name: str, library: str, *, import_library: str | None = None,
                  static_link: list[str] | None = None) -> str:
    lines = [f"if(NOT TARGET vpn-core::{name})",
             f"  add_library(vpn-core::{name} UNKNOWN IMPORTED GLOBAL)"]
    properties = [
        f'IMPORTED_LOCATION "${{_VPN_CORE_PREFIX}}/lib/{library}"',
        'INTERFACE_INCLUDE_DIRECTORIES "${_VPN_CORE_PREFIX}/include"',
    ]
    if import_library:
        properties.append(f'IMPORTED_IMPLIB "${{_VPN_CORE_PREFIX}}/lib/{import_library}"')
    lines.append("  set_target_properties(vpn-core::" + name + " PROPERTIES\n  " +
                 "\n  ".join(properties) + "\n)")
    if static_link:
        rendered = "\n".join(f"  {_cmake_quote(argument)}" for argument in static_link)
        lines.extend((f"  set(_VPN_CORE_STATIC_LINK_ARGS\n{rendered}\n  )",
                      "  set_property(TARGET vpn-core::static PROPERTY INTERFACE_LINK_LIBRARIES "
                      '"${_VPN_CORE_STATIC_LINK_ARGS}")'))
    lines.append("endif()")
    return "\n".join(lines)


def generate_metadata(stage: Path, platform: str, version: str, static_arguments: list[str]) -> None:
    """Write metadata beside the libraries using only package-relative paths."""
    static_arguments = validate_link_arguments(static_arguments)
    libraries = sorted(path.name for path in (stage / "lib").iterdir() if path.is_file())
    static_libraries = [name for name in libraries if name.endswith((".a", ".lib")) and not name.endswith(".dll.lib")]
    shared_libraries = [name for name in libraries if name.endswith((".so", ".dylib", ".dll"))]
    import_libraries = [name for name in libraries if name.endswith(".dll.lib")]
    if not static_libraries:
        raise ValueError(f"SDK platform {platform} has no static library")
    if platform == "windows-x86_64" and shared_libraries and not import_libraries:
        raise ValueError("Windows shared SDK requires an import library")

    cmake_dir = stage / "cmake" / "vpn-core"
    cmake_dir.mkdir(parents=True, exist_ok=True)
    default_target = "shared" if shared_libraries else "static"
    config = [
        "# Generated by scripts/ffi_sdk_metadata.py; paths are relative to this file.",
        'get_filename_component(_VPN_CORE_PREFIX "${CMAKE_CURRENT_LIST_DIR}/../.." ABSOLUTE)',
    ]
    if shared_libraries:
        config.append(_cmake_target(
            "shared", shared_libraries[0],
            import_library=import_libraries[0] if import_libraries else None,
        ))
    config.append(_cmake_target("static", static_libraries[0], static_link=static_arguments))
    config.extend((
        "if(NOT TARGET vpn-core::vpn-core)",
        "  add_library(vpn-core::vpn-core INTERFACE IMPORTED GLOBAL)",
        f"  set_property(TARGET vpn-core::vpn-core PROPERTY INTERFACE_LINK_LIBRARIES vpn-core::{default_target})",
        "endif()",
        'set(vpn-core_VERSION "' + _cmake_version(version) + '")',
        "unset(_VPN_CORE_PREFIX)",
    ))
    (cmake_dir / "vpn-coreConfig.cmake").write_text("\n\n".join(config) + "\n", encoding="utf-8")
    (cmake_dir / "vpn-coreConfigVersion.cmake").write_text(
        _cmake_version_file(version), encoding="utf-8"
    )

    if platform in PC_PLATFORMS:
        pc_dir = stage / "lib" / "pkgconfig"
        pc_dir.mkdir(parents=True, exist_ok=True)
        private = shlex.join(static_arguments)
        content = (
            "prefix=${pcfiledir}/../..\n"
            "libdir=${prefix}/lib\n"
            "includedir=${prefix}/include\n\n"
            "Name: vpn-core\n"
            "Description: VPN Core C ABI library\n"
            f"Version: {_pc_version(version)}\n"
            "Libs: -L${libdir} -lreality\n"
            + (f"Libs.private: {private}\n" if private else "")
            + "Cflags: -I${includedir}\n"
        )
        (pc_dir / "vpn-core.pc").write_text(content, encoding="utf-8")


def _pc_version(version: str) -> str:
    return version if re.fullmatch(r"\d+\.\d+\.\d+(?:[-+][A-Za-z0-9.-]+)?", version) else "0.0.0"


def _cmake_version(version: str) -> str:
    return _pc_version(version)


def _cmake_version_file(version: str) -> str:
    version = _cmake_version(version)
    return (
        f'set(PACKAGE_VERSION "{version}")\n'
        "if(PACKAGE_FIND_VERSION_RANGE)\n"
        "  set(PACKAGE_VERSION_COMPATIBLE FALSE)\n"
        "elseif(PACKAGE_FIND_VERSION VERSION_GREATER PACKAGE_VERSION)\n"
        "  set(PACKAGE_VERSION_COMPATIBLE FALSE)\n"
        "else()\n"
        "  set(PACKAGE_VERSION_COMPATIBLE TRUE)\n"
        "  if(PACKAGE_FIND_VERSION STREQUAL PACKAGE_VERSION)\n"
        "    set(PACKAGE_VERSION_EXACT TRUE)\n"
        "  endif()\n"
        "endif()\n"
    )
